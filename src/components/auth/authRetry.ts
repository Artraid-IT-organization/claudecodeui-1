/**
 * Пауза перед повторной проверкой авторизации.
 *
 * Проверка делается один раз при запуске приложения. Если ровно в этот момент
 * связи нет — а на телефоне это обычное дело, — человек получает надпись
 * «Failed to check authentication status» и **тупик**: страница больше ничего
 * не спрашивает и ждёт, пока её перезагрузят руками. Поймано 20.09.26: экран
 * простоял с этой надписью больше получаса, и в журнале сервера за это время
 * не было ни одного запроса с устройства — молчала страница, а не сервер.
 *
 * Отсюда правило: пауза растёт (не долбить сервер, которому и так плохо), но
 * имеет потолок — иначе к вечеру повтор ждал бы часами и человек всё равно
 * остался бы с мёртвым экраном.
 */
export const AUTH_RETRY_BASE_MS = 5_000;
export const AUTH_RETRY_MAX_MS = 30_000;

export const nextAuthRetryDelay = (
  attempt: number,
  base = AUTH_RETRY_BASE_MS,
  max = AUTH_RETRY_MAX_MS,
): number => {
  // Первая попытка — она же нулевая: ждать дольше базовой паузы незачем.
  const safeAttempt = Number.isFinite(attempt) && attempt > 0 ? Math.floor(attempt) : 0;
  const delay = base * 2 ** safeAttempt;
  return Math.min(delay, max);
};
